#!/usr/bin/env node
// Zero-dependency generator for the `src/` toolbox catalog (`src/README.md`).
//
// The catalog is a projection of what is actually on disk: it discovers every
// `src/<module>/package.json` (top-level dirs only, mirroring the discovery in
// `scripts/test-all.mjs`) and renders a deterministic README from each
// module's `name` / `description` / `main`. Because the file is generated, it
// can never silently drift from the modules — the `--check` mode is wired into
// CI to fail any PR whose committed `src/README.md` differs from a fresh render.
//
// Modes:
//   (no args)   WRITE  — render and overwrite `src/README.md`.
//   --check     VERIFY — render in memory, diff against the committed file, and
//                        exit 1 (with a fix hint) when they differ; exit 0 when
//                        they match. This is the drift gate.
//
// Uses Node built-ins only — no runtime dependencies.

import { readdirSync, existsSync, readFileSync, writeFileSync, statSync } from 'node:fs';
import { join, dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const srcDir = join(repoRoot, 'src');
const readmePath = join(srcDir, 'README.md');

const BANNER =
  '<!-- GENERATED by scripts/gen-toolbox-readme.mjs — do not edit by hand; run `node scripts/gen-toolbox-readme.mjs` -->';

// Discover top-level `src/<module>/` dirs that carry a `package.json`, exactly
// as `scripts/test-all.mjs` does (README.md and non-dir entries fall away).
// Sorted alphabetically for deterministic output.
function discoverModules() {
  if (!existsSync(srcDir)) return [];
  return readdirSync(srcDir)
    .map((name) => ({ name, dir: join(srcDir, name) }))
    .filter(({ dir }) => {
      try {
        return statSync(dir).isDirectory();
      } catch {
        return false;
      }
    })
    .filter(({ dir }) => existsSync(join(dir, 'package.json')))
    .map(({ name, dir }) => ({
      name,
      pkg: JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8')),
    }))
    .sort((a, b) => a.name.localeCompare(b.name));
}

// The module's entry path relative to `src/`, e.g. `retry/retry.ts`. `main`
// may carry a leading `./` (Node allows it); strip it so the rendered path is
// clean. Fall back to `index.js` — Node's default — when `main` is absent.
function entryPath(name, pkg) {
  const main = (pkg.main ?? 'index.js').replace(/^\.\//, '');
  return `${name}/${main}`;
}

// First sentence of a description: text up to and including the first
// sentence-ending `.` `!` or `?` that is followed by whitespace or end-of-string.
// This keeps parenthetical `.`-containing clauses intact (e.g. an inner
// "...at process start)." boundary) while trimming trailing sentences.
function firstSentence(desc) {
  const text = (desc ?? '').trim();
  if (!text) return '';
  const m = text.match(/^.*?[.!?](?=\s|$)/s);
  return (m ? m[0] : text).trim();
}

function renderTable(modules) {
  const rows = modules.map(({ name, pkg }) => {
    const what = firstSentence(pkg.description) || '(no description)';
    const entry = `\`${entryPath(name, pkg)}\``;
    return `| [${name}](./${name}/) | ${what} | ${entry} |`;
  });
  return ['| Module | What it does | Entry |', '|---|---|---|', ...rows].join('\n');
}

function render(modules) {
  return `${BANNER}

# src — zero-dependency utility toolbox

This directory is the zero-dependency utility toolbox of the sandbox monorepo.
Every module under \`src/\` is pure, dependency-free (no runtime \`node_modules\`
required to import it), and independently tested. CI auto-discovers each module
by the presence of a \`package.json\` with a \`"test"\` script
(\`scripts/test-all.mjs\`) and gates the build on all of them.

This catalog is generated from the modules on disk — do not edit it by hand.
Run \`node scripts/gen-toolbox-readme.mjs\` to regenerate it; CI fails any change
where the committed file has drifted from a fresh render.

## Modules

${renderTable(modules)}

## Conventions

- **Zero runtime dependencies.** Each module imports only Node built-ins.
  \`devDependencies\` (e.g. TypeScript, vitest) are allowed in modules that need a
  build or typed test runner, but nothing that must be present at import time.
- **Node v24+, native ESM.** Modules declare \`"type": "module"\` and use \`.mjs\`
  or \`.ts\` entry points — no CommonJS, no transpilation step for the pure-JS
  modules.
- **Colocated tests.** Each module's tests live alongside its source and run
  under the module's own declared runner (\`node --test\` for the pure-JS
  modules, \`vitest\` for the TypeScript module). No shared test harness.
- **One module, one concern.** Modules do not depend on each other. Each is a
  standalone leaf that can be copied or vendored independently.

## Running tests

From the repo root, run the suite: \`node scripts/test-all.mjs\`
`;
}

function main() {
  const check = process.argv.includes('--check');
  const modules = discoverModules();
  const rendered = render(modules);

  if (!check) {
    writeFileSync(readmePath, rendered);
    console.log(`Wrote ${modules.length} module(s) to src/README.md`);
    return;
  }

  const committed = existsSync(readmePath) ? readFileSync(readmePath, 'utf8') : '';
  if (committed === rendered) {
    console.log('src/README.md is up to date.');
    process.exit(0);
  }

  console.error(
    'src/README.md is stale — run `node scripts/gen-toolbox-readme.mjs` to regenerate it.',
  );
  // Point at the first differing line to make the drift concrete.
  const a = committed.split('\n');
  const b = rendered.split('\n');
  const max = Math.max(a.length, b.length);
  for (let i = 0; i < max; i++) {
    if (a[i] !== b[i]) {
      console.error(`  first diff at line ${i + 1}:`);
      console.error(`    committed: ${a[i] ?? '(end of file)'}`);
      console.error(`    expected:  ${b[i] ?? '(end of file)'}`);
      break;
    }
  }
  process.exit(1);
}

main();
